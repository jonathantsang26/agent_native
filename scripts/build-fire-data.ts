/**
 * Bundles the fire files the agent's actions read into the server build.
 *
 * Server code can't read public/ at runtime on serverless hosts, so actions
 * import the files instead. JSON files are imported straight from
 * public/data/<fire>/. GeoJSON files are copied here with a .json extension
 * (the server bundler only imports .json), and arrival.png is inlined as
 * base64. Re-run after changing anything under public/data:
 *
 *   pnpm fire-data
 */
import { copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outDir = path.join(root, "server/lib/fire/bundled");

const FIRES = ["eaton", "palisades"];
const JSON_FILES = [
  "aoi.json",
  "dem.json",
  "labels.json",
  "gazetteer.json",
  "series.json",
  "weather.json",
  "events.json",
  "ignition.json",
  "exposure_stats.json",
];
const GEOJSON_FILES = [
  "final_perimeter.geojson",
  "roads.geojson",
  "spine.geojson",
  "structures.geojson",
];

rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

const entries: string[] = [];
for (const fire of FIRES) {
  const src = path.join(root, "public/data", fire);
  mkdirSync(path.join(outDir, fire), { recursive: true });
  const lines: string[] = [];
  for (const file of JSON_FILES) {
    if (!existsSync(path.join(src, file))) continue;
    lines.push(
      `      ${JSON.stringify(file)}: (await import("../../../../public/data/${fire}/${file}")).default,`,
    );
  }
  for (const file of GEOJSON_FILES) {
    if (!existsSync(path.join(src, file))) continue;
    const copy = file.replace(/\.geojson$/, ".json");
    copyFileSync(path.join(src, file), path.join(outDir, fire, copy));
    lines.push(
      `      ${JSON.stringify(file)}: (await import("./${fire}/${copy}")).default,`,
    );
  }
  const png = readFileSync(path.join(src, "arrival.png")).toString("base64");
  writeFileSync(
    path.join(outDir, fire, "arrival.ts"),
    `// Generated by scripts/build-fire-data.ts from public/data/${fire}/arrival.png.\nexport default ${JSON.stringify(png)};\n`,
  );
  entries.push(`  ${fire}: async () => ({
    json: {
${lines.join("\n")}
    },
    bytes: {
      "arrival.png": (await import("./${fire}/arrival.js")).default,
    },
  }),`);
}

writeFileSync(
  path.join(outDir, "index.ts"),
  `// Generated by scripts/build-fire-data.ts. Do not edit; run \`pnpm fire-data\`.
/* eslint-disable */

export type BundledFire = {
  json: Record<string, unknown>;
  /** base64 */
  bytes: Record<string, string>;
};

export const BUNDLED_FIRES: Record<string, () => Promise<BundledFire>> = {
${entries.join("\n")}
};
`,
);

console.log(`Bundled ${FIRES.length} fires into ${path.relative(root, outDir)}`);
